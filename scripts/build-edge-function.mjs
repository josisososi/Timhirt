// Builds the deployable single-file Supabase function (supabase/functions/study-chat/index.ts)
// from books.ts (generated from the canon list) + logic.ts + handler.ts, because pasting one
// file into the Supabase dashboard is the simplest way to deploy. Run: npm run build:edge
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'functions', 'study-chat');
const canon = JSON.parse(readFileSync(join(root, 'src', 'data', 'canon.json'), 'utf8'));

const names = canon.map((b) => b.tag_name);
const books = `// GENERATED from src/data/canon.json by scripts/build-edge-function.mjs. Do not edit.
export const BOOK_NAMES: string[] = ${JSON.stringify(names)};
`;
writeFileSync(join(dir, 'books.ts'), books);

const stripLocalImports = (src) => src.replace(/^import .* from '\.\/[a-z]+\.ts';\r?\n/gm, '');
const read = (f) => readFileSync(join(dir, f), 'utf8');

// Imports must come first in a module, so keep handler's package imports at the top.
const handler = stripLocalImports(read('handler.ts'));
const handlerImports = handler.match(/^import .*$/gm) ?? [];
const handlerBody = handler.replace(/^import .*\r?\n/gm, '');

const out = [
  '// GENERATED by scripts/build-edge-function.mjs from books.ts, logic.ts and handler.ts.',
  '// Do not edit this file: edit the sources and run `npm run build:edge`.',
  ...handlerImports,
  '',
  books.split('\n').slice(1).join('\n'),
  stripLocalImports(read('logic.ts')),
  handlerBody,
].join('\n');

writeFileSync(join(dir, 'index.ts'), out);
console.log(`wrote ${join(dir, 'index.ts')} (${out.length} chars, ${names.length} books)`);
